// init mischt die Datei-Manager-Texte in die Zusatztexte ein.
//
// @date   2026-10-21 19:45
func init() {
	for lang, texts := range fileManagerTranslations {
		if extraTranslations[lang] == nil {
			extraTranslations[lang] = map[textKey]string{}
		}
		for key, text := range texts {
			extraTranslations[lang][key] = text
		}
	}
}

